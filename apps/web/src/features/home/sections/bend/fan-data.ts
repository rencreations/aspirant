/**
 * The fan pictures of the bend section: the group pictures of The Aspirants that the media workstream
 * picked (`public/data/home/picks.json`, `fanart.items`), with the credit each one is shown with.
 * Two group pictures with no named artist are left out there. `pictures.test.ts` keeps this file
 * equal to the picks. It is small on purpose, because `preload.ts` is in the bundle of every page.
 */
import type { Canon } from "@/features/library/types";

export interface FanPic {
  id: string;
  /** What the picture is: fan work, every one here. The takedown link and the badge follow it. */
  canon: Canon;
  title: string;
  alt: string;
  /** The Aspirants in the picture (a group). */
  chars: readonly string[];
  /** The 1280 wide picture in the library (`libUrl` makes the address). */
  key: string;
  w: number;
  h: number;
  /** Bytes of the `p` file. */
  bytes: number;
  /** The mean colour of the picture: a card shows it until the picture has arrived. */
  color: string;
  creditLine: string;
  /** Who made it, where, and the original post. */
  credit: { by: string; platform: string; url: string };
  /** The text of the credit's link: the artist as the post names them. */
  artistLink: string;
  report: { item: string; title: string };
}

