"""Tracks the three touch points of Obsidia's page through the idle loop.

The idle animation sways, so a dot placed once would slide off the weapon's head, her face or her
boot. This follows a patch of the picture around each point from frame to frame (phase
correlation) and writes where the point is at every third frame of the loop. The page reads it
at the idle video's time, so each dot stays on its spot.

The loop is seamless (its last frames dissolve into its first), so the point ends where it began.
Whatever the tracking has drifted by is taken out in a straight ramp, then the path is smoothed.

Run: python -I scripts/obsidia/track.py <scratch folder for the check sheet>
Needs ffmpeg, numpy, scipy and scikit-image. Reads the 1080 idle video, writes
apps/web/src/features/character/obsidia/hotspots.generated.ts and a check sheet in the scratch
folder given as the first argument (optional).
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import gaussian_filter1d
from skimage.registration import phase_cross_correlation

W, H = 960, 432  # tracking size (half of the 1080 tier)
PATCH = 80
STEP = 2  # frames between stored samples (482 frames of the loop make 241 samples)

# id -> (x, y) as a fraction of the picture, on the first frame of the loop
POINTS = {
    "weapon": (0.216, 0.600),
    "face": (0.630, 0.190),
    "feet": (0.466, 0.810),
}


def frames(video: Path):
    p = subprocess.Popen(
        ["ffmpeg", "-v", "error", "-i", str(video), "-vf", f"scale={W}:{H}:flags=area,format=gray",
         "-f", "rawvideo", "-pix_fmt", "gray", "-"],
        stdout=subprocess.PIPE,
    )
    size = W * H
    while True:
        buf = p.stdout.read(size)
        if len(buf) < size:
            break
        yield np.frombuffer(buf, dtype=np.uint8).reshape(H, W).astype(np.float32)
    p.wait()


def crop(img: np.ndarray, cx: float, cy: float) -> np.ndarray:
    x0 = int(round(cx)) - PATCH // 2
    y0 = int(round(cy)) - PATCH // 2
    x0 = min(max(x0, 0), W - PATCH)
    y0 = min(max(y0, 0), H - PATCH)
    return img[y0 : y0 + PATCH, x0 : x0 + PATCH]


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    video = root / "apps/web/public/video/obsidia/1080/idle.mp4"
    sheet_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    win = np.outer(np.hanning(PATCH), np.hanning(PATCH)).astype(np.float32)

    pos = {k: [(x * W, y * H)] for k, (x, y) in POINTS.items()}
    prev = None
    first = None
    kept = []
    for i, img in enumerate(frames(video)):
        if i % 80 == 0:
            kept.append(img)
        if prev is None:
            prev = img
            first = img
            continue
        for k in POINTS:
            cx, cy = pos[k][-1]
            a = crop(prev, cx, cy)
            b = crop(img, cx, cy)
            a = (a - a.mean()) * win
            b = (b - b.mean()) * win
            shift, _err, _ph = phase_cross_correlation(a, b, upsample_factor=20, normalization=None)
            pos[k].append((cx - shift[1], cy - shift[0]))
        prev = img
    n = len(pos["face"])
    print("frames", n)

    out = {}
    for k, pts in pos.items():
        a = np.array(pts, dtype=np.float64)
        closure = a[-1] - a[0]
        ramp = np.linspace(0, 1, n)[:, None] * closure[None, :]
        a = a - ramp
        a = gaussian_filter1d(a, sigma=2.0, axis=0, mode="wrap")
        print(k, "closure drift px", np.round(closure, 1), "range x", round(float(np.ptp(a[:, 0])), 1), "y", round(float(np.ptp(a[:, 1])), 1))
        norm = np.stack([a[:, 0] / W, a[:, 1] / H], axis=1)
        out[k] = [[round(float(x), 4), round(float(y), 4)] for x, y in norm[::STEP]]

    dest = root / "apps/web/src/features/character/obsidia/hotspots.generated.ts"
    body = json.dumps(out)
    dest.write_text(
        "// Generated by scripts/obsidia/track.py. Do not edit.\n\n"
        f"/** Frames between two stored positions. */\nexport const HOTSPOT_STEP = {STEP};\n\n"
        "/** Where each touch point is (a fraction of the picture) every `HOTSPOT_STEP` frames of the idle loop. */\n"
        f"export const HOTSPOT_PATHS: Record<\"weapon\" | \"face\" | \"feet\", ReadonlyArray<readonly [number, number]>> = {body};\n",
        encoding="utf-8",
    )
    print("wrote", dest)

    if sheet_dir:
        sheet_dir.mkdir(parents=True, exist_ok=True)
        # check sheet: the picture at five moments with the tracked points
        idx = [0, 120, 240, 360, 480]
        vid = frames(video)
        wanted = {}
        for i, img in enumerate(vid):
            if i in idx:
                wanted[i] = img
            if i >= idx[-1]:
                break
        tiles = []
        for i in idx:
            im = Image.fromarray(wanted[i].astype(np.uint8)).convert("RGB")
            d = ImageDraw.Draw(im)
            for k, path in out.items():
                x, y = path[min(i // STEP, len(path) - 1)]
                cx, cy = x * W, y * H
                d.ellipse((cx - 16, cy - 16, cx + 16, cy + 16), outline=(255, 255, 0), width=2)
            tiles.append(im.crop((0, 0, W, H)).resize((480, 216)))
        sheet = Image.new("RGB", (480 * 2, 216 * 3))
        for j, t in enumerate(tiles):
            sheet.paste(t, ((j % 2) * 480, (j // 2) * 216))
        sheet.save(sheet_dir / "track-sheet.png")


if __name__ == "__main__":
    main()
