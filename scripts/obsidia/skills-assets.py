"""
Builds the clips and pictures of Obsidia's Skills page from the official skin showcase video and
the skill icons.

Source video: skin-showcase.webm (1920x1080, 30 fps). Only Obsidia's parts are used: her own
cinematics and gameplay (frames 16.5 to 40 s, found by scene detection and by reading the skill
bar on screen, which lights the skill that is being cast), and the left half of the split-screen
idle and interactive animation (Selena is on the right half and is cropped away).

Output: apps/web/public/video/obsidia/skills/<id>.mp4 (and .webp poster), <id>-s.mp4 (the small,
        silent loop shown in the corner) and apps/web/public/img/obsidia/skills/<icon>.webp

The small loop is 960 pixels wide at most and runs at 60 fps like the page (a 30 fps video beside
the live 60 fps picture makes the browser pace the whole page at half rate). The full clip (with
sound) opens in the player.

Run: python -I scripts/obsidia/skills-assets.py "D:/ren/aspirant/media/selena-and-obsidia/skin-showcase.webm" "D:/ren/aspirant/media/others/skills-icon/obsidia"
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

# id -> (start, end, crop filter or None)
CLIPS = {
    "needle": (30.5, 34.0, None),
    "shadowmeld": (34.0, 36.85, None),
    "hunt": (36.9, 40.0, None),
    "fight": (19.7, 23.7, None),
    "intro": (16.5, 19.66, None),
    "burst": (23.75, 27.3, None),
    "idle": (84.1, 101.9, "crop=960:920:0:0"),
    "interactive": (102.0, 108.4, "crop=960:920:0:0"),
}


def run(args: list[str]) -> None:
    p = subprocess.run(["ffmpeg", "-v", "error", "-y", *args], capture_output=True, text=True)
    if p.returncode:
        raise SystemExit(p.stderr)


def small(clip: Path) -> Path:
    """The silent, small loop of a clip: 960 pixels wide at most, at 60 fps.

    The page's own picture runs at 60 fps. A second video at 30 fps beside it makes the browser
    pace every frame of the page at half the screen's rate, so the loop is made at 60 (each frame
    twice, which costs almost nothing in size).
    """
    out = clip.with_name(f"{clip.stem}-s.mp4")
    run([
        "-i", str(clip), "-an",
        "-vf", "scale='min(960,iw)':-2:flags=lanczos,setsar=1,format=yuv420p,fps=60",
        "-c:v", "libx264", "-preset", "slow", "-crf", "29", "-profile:v", "high",
        "-g", "60", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
        str(out),
    ])
    return out


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    # --previews-only: keep the clips and posters as they are, and only make the small loops
    # (the clips are cut already, so the source video is not needed).
    previews_only = "--previews-only" in sys.argv
    video = Path(args[0]) if args else Path()
    icons = Path(args[1]) if len(args) > 1 else Path()
    root = Path(__file__).resolve().parents[2]
    web = root / "apps" / "web" / "public"
    out_v = web / "video" / "obsidia" / "skills"
    out_i = web / "img" / "obsidia" / "skills"
    out_v.mkdir(parents=True, exist_ok=True)
    out_i.mkdir(parents=True, exist_ok=True)

    meta = {}
    for key, (a, b, crop) in CLIPS.items():
        target = out_v / f"{key}.mp4"
        if not previews_only:
            vf = ",".join(x for x in (crop, "setsar=1", "format=yuv420p") if x)
            run([
                "-ss", str(a), "-to", str(b), "-i", str(video),
                "-vf", vf,
                "-c:v", "libx264", "-preset", "slow", "-crf", "27", "-profile:v", "high",
                "-g", "30", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
                "-c:a", "aac", "-b:a", "96k", "-ar", "48000", "-ac", "2",
                str(target),
            ])
            run([
                "-ss", str(a + min(0.6, (b - a) / 3)), "-i", str(video), "-frames:v", "1",
                "-vf", ",".join(x for x in (crop, "scale=960:-2:flags=lanczos") if x),
                "-c:v", "libwebp", "-quality", "78", str(out_v / f"{key}.webp"),
            ])
        meta[key] = {
            "seconds": round(b - a, 2),
            "bytes": target.stat().st_size,
            "smallBytes": small(target).stat().st_size,
            "portrait": crop is not None,
        }
        print(key, round(b - a, 2), "s", target.stat().st_size // 1024, "KB")

    if not previews_only:
        for f in sorted(icons.glob("*.webp")):
            shutil.copy2(f, out_i / f.name)
        print("icons", len(list(out_i.glob("*.webp"))))
    dest = root / "apps" / "web" / "src" / "features" / "character" / "obsidia" / "skills"
    dest.mkdir(parents=True, exist_ok=True)
    body = json.dumps(meta, indent=2)
    header = (
        "// Generated by scripts/obsidia/skills-assets.py. Do not edit.\n\n"
        "export interface SkillClipMeta {\n"
        "  seconds: number;\n"
        "  bytes: number;\n"
        "  /** The small silent loop next to the list. */\n"
        "  smallBytes: number;\n"
        "  /** Cropped to Obsidia's half of the split screen. */\n"
        "  portrait: boolean;\n"
        "}\n\n"
    )
    (dest / "clips.generated.ts").write_text(
        header + f"export const SKILL_CLIPS = {body} as const satisfies Record<string, SkillClipMeta>;\n",
        encoding="utf-8",
    )
    print("wrote clips.generated.ts")


if __name__ == "__main__":
    main()
