"""
Builds the art of Obsidia's Gallery page.

Art: the official pieces and the fan art, as webp (a full size for the viewer and a small one for
the grid). The HEIC photos from Instagram are converted (this needs `pip install pillow-heif`).
The trailer, the Day of Enders trailer and the TikTok are the files of Selena's Gallery and of her
main panel: they are not built again (see gallery-media.ts).

Output: apps/web/public/img/obsidia/gallery/<id>.webp and <id>-t.webp,
        apps/web/src/features/character/obsidia/gallery/gallery-media.generated.ts

Run: python -I scripts/obsidia/gallery-assets.py "D:/ren/aspirant/media/selena-and-obsidia"
"""

import json
import sys
from pathlib import Path

import pillow_heif
from PIL import Image, ImageOps

pillow_heif.register_heif_opener()

# id -> source, relative to the media folder. The ids are used by gallery-data.ts.
OFFICIAL = {
    "official-splash": "official/obsidia/obsidia-splash-art.png",
    "official-queens-endgame": "official/obsidia/obsidia.jpg",
    "official-day-of-enders": "official/obsidia/aspirant.jpg",
}

FAN = "fanart/obsidia/"
FANART = {
    "fan-falguni_shikder": FAN + "httpswww.instagram.comfalguni_shikder.jpg",
    "fan-haniwa_.20": FAN + "httpswww.instagram.comhaniwa_.20.jpg",
    "fan-kitemo_chan": FAN + "httpswww.instagram.comkitemo_chan - obisidia.jpeg",
    "fan-lococo20220304": FAN + "httpswww.instagram.comlococo20220304.jpg",
    "fan-ig-Db_FVUklFvn": FAN + "httpswww.instagram.compDb_FVUklFvn.heic",
    "fan-ig-DcCCUwTTTo8": FAN + "httpswww.instagram.compDcCCUwTTTo8.heic",
    "fan-reddit-1tgcg5b": FAN + "httpswww.reddit.comrMobileLegendsGamecomments1tgcg5bobsidia_fanart_commision.png",
}

FULL_EDGE = 2560  # longest edge of the full size
THUMB_BOX = (720, 960)


def convert_image(src: Path, out_dir: Path, name: str) -> dict:
    im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
    full = im.copy()
    if max(full.size) > FULL_EDGE:
        full.thumbnail((FULL_EDGE, FULL_EDGE), Image.LANCZOS)
    full_path = out_dir / f"{name}.webp"
    full.save(full_path, quality=88, method=6)
    thumb = im.copy()
    thumb.thumbnail(THUMB_BOX, Image.LANCZOS)
    thumb_path = out_dir / f"{name}-t.webp"
    thumb.save(thumb_path, quality=80, method=6)
    return {
        "w": full.width,
        "h": full.height,
        "bytes": full_path.stat().st_size,
        "tw": thumb.width,
        "th": thumb.height,
        "tbytes": thumb_path.stat().st_size,
    }


def main() -> None:
    media = Path(sys.argv[1])
    root = Path(__file__).resolve().parents[2]
    web = root / "apps" / "web"
    img_dir = web / "public" / "img" / "obsidia" / "gallery"
    img_dir.mkdir(parents=True, exist_ok=True)

    images: dict[str, dict] = {}
    for name, rel in {**OFFICIAL, **FANART}.items():
        images[name] = convert_image(media / rel, img_dir, name)
        print(name, images[name]["w"], "x", images[name]["h"], images[name]["bytes"] // 1024, "KB")

    dest = web / "src" / "features" / "character" / "obsidia" / "gallery"
    dest.mkdir(parents=True, exist_ok=True)
    body = (
        "// Generated by scripts/obsidia/gallery-assets.py. Do not edit.\n\n"
        'import type { GalleryImageMeta } from "../../selena/gallery/gallery-media.generated";\n\n'
        f"export const GALLERY_IMAGES = {json.dumps(images, indent=2)} as const satisfies Record<string, GalleryImageMeta>;\n"
    )
    (dest / "gallery-media.generated.ts").write_text(body, encoding="utf-8")
    print("wrote gallery-media.generated.ts")


if __name__ == "__main__":
    main()
