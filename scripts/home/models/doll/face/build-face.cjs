// Writes face.glsl (from face.glsl.in and params.json) and presets.json (from presets.src.cjs).
//
//   node scripts/home/models/doll/face/build-face.cjs
//
// Checks on the way: every preset names only known floats, every value is inside the range of its
// float, every float used by the shader exists, and the shader's macros are in the order of the array.
const fs = require("node:fs");
const path = require("node:path");

const here = __dirname;
const { params, frame } = JSON.parse(fs.readFileSync(path.join(here, "params.json"), "utf8"));
const source = require("./presets.src.cjs");

const names = params.map((p) => p[0]);
if (new Set(names).size !== names.length) throw new Error("a float is named twice");
if (names.length > 56) throw new Error(`${names.length} floats do not fit the array of 56`);
const defaults = Object.fromEntries(params.map((p) => [p[0], p[1]]));
const range = Object.fromEntries(params.map((p) => [p[0], [p[2], p[3]]]));

const out = {};
for (const [name, over] of Object.entries(source)) {
  for (const [key, value] of Object.entries(over)) {
    if (!(key in defaults)) throw new Error(`preset ${name}: there is no float ${key}`);
    const [lo, hi] = range[key];
    if (value < lo || value > hi)
      throw new Error(`preset ${name}: ${key} ${value} is outside ${lo}..${hi}`);
  }
  // Every preset is a full set, in the order of the array.
  const full = {};
  for (const key of names) full[key] = key in over ? over[key] : defaults[key];
  out[name] = full;
}

const template = fs.readFileSync(path.join(here, "face.glsl.in"), "utf8");
const defines = names.map((n, i) => `#define F_${n} uFaceF[${i}]`).join("\n");
const glsl = template.replace("//@PARAMS", defines);
for (const used of new Set([...glsl.matchAll(/\bF_(\w+)\b/g)].map((m) => m[1]))) {
  if (!names.includes(used))
    throw new Error(`the shader uses F_${used}, which params.json does not have`);
}
const header =
  "// GENERATED by build-face.cjs from face.glsl.in and params.json: edit those, not this.\n";
fs.writeFileSync(path.join(here, "face.glsl"), header + glsl);

const json = {
  note: "Every expression of the doll as a full set of the floats of the shader's uniform array `uFaceF`, in the order of `names`. `frame` is where the face is, see params.json.",
  size: 56,
  names,
  defaults,
  ranges: range,
  frame,
  presets: out,
};
fs.writeFileSync(path.join(here, "presets.json"), `${JSON.stringify(json, null, 2)}\n`);
console.log(
  `${names.length} floats, ${Object.keys(out).length} expressions: ${Object.keys(out).join(", ")}`,
);
