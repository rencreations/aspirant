"""Cut the ten short clips of the roster intro from the game's welcome recordings
and write the manifest the intro engine reads.

Run with the anaconda Python (isolated mode is fine):
    C:\\Users\\muham\\anaconda3\\python.exe -I scripts\\roster-intro\\build.py [slug ...]

Each clip is 1600x720 (the recordings are 3840x1728, the same shape), 60 fps, H.264,
no audio, a keyframe every 12 frames (so it seeks well), +faststart.
To recut a clip: change its row in CLIPS (start time in the SOURCE, in seconds, length,
and the focus point as fractions of the frame), then run the script again. The manifest
apps/web/src/features/character/roster/intro/clips.generated.ts is rewritten every run.
"""

import os
import subprocess
import sys

SRC = r"D:\ren\aspirant\media\game\animation\{slug}\welcome.mkv"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_DIR = os.path.join(ROOT, "apps", "web", "public", "video", "roster-intro")
MANIFEST = os.path.join(
    ROOT, "apps", "web", "src", "features", "character", "roster", "intro", "clips.generated.ts"
)

# a clip that comes out above 1.5 MB gets a higher crf here
CRF = {"lesley": 30}

# slug: (start in the source, length, focus x, focus y)
# The order is the roster's: it is also the order of the manifest.
CLIPS = {
    "obsidia": (10.6, 1.5, 0.50, 0.42),
    "selena": (5.3, 1.4, 0.42, 0.45),
    "vexana": (4.6, 1.5, 0.50, 0.45),
    "guinevere": (2.4, 1.5, 0.50, 0.45),
    "lesley": (8.6, 1.5, 0.60, 0.50),
    "change": (7.6, 1.5, 0.62, 0.45),
    "ruby": (8.3, 1.4, 0.46, 0.45),
    "angela": (5.2, 1.4, 0.45, 0.50),
    "layla": (5.1, 1.2, 0.55, 0.42),
    "fanny": (8.2, 1.4, 0.50, 0.50),
}


def cut(slug, start, length):
    out = os.path.join(OUT_DIR, slug + ".mp4")
    cmd = [
        "ffmpeg", "-v", "error", "-y",
        "-ss", f"{start:.3f}", "-t", f"{length:.3f}",
        "-i", SRC.format(slug=slug),
        "-an",
        "-vf", "scale=1600:720:flags=lanczos,fps=60,format=yuv420p",
        "-c:v", "libx264", "-preset", "slow", "-crf", str(CRF.get(slug, 28)),
        "-g", "12", "-keyint_min", "12", "-sc_threshold", "0",
        "-movflags", "+faststart",
        out,
    ]
    subprocess.run(cmd, check=True)
    return out, os.path.getsize(out)


def write_manifest():
    lines = [
        "// Generated by scripts/roster-intro/build.py. Do not edit by hand.",
        'import type { Slug } from "@/content/types";',
        "",
        "export interface IntroClip {",
        "  slug: Slug;",
        "  src: string;",
        "  from: number;",
        "  duration: number;",
        "  width: 1600;",
        "  height: 720;",
        "  focus: { x: number; y: number };",
        "}",
        "",
        "export const INTRO_CLIPS: Record<Slug, IntroClip> = {",
    ]
    for slug, (start, length, fx, fy) in CLIPS.items():
        lines += [
            f'  {slug}: {{',
            f'    slug: "{slug}",',
            f'    src: "/video/roster-intro/{slug}.mp4",',
            f"    from: {start},",
            f"    duration: {length},",
            "    width: 1600,",
            "    height: 720,",
            f"    focus: {{ x: {fx}, y: {fy} }},",
            "  },",
        ]
    lines += ["};", ""]
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    only = sys.argv[1:] or list(CLIPS)
    for slug in only:
        start, length, _, _ = CLIPS[slug]
        out, size = cut(slug, start, length)
        print(f"{slug:10s} from {start:5.2f}s  {length:.2f}s  {size / 1024:7.0f} KB  {out}")
    write_manifest()
    print("manifest written")


if __name__ == "__main__":
    main()
